// Typed Java classes for the Daml model, generated by dpm from the built DAR.
// Build the DAR first with `make build` at the repo root.
val damlDar = layout.projectDirectory.file("../daml/loan-model/.daml/dist/loan-model-0.1.0.dar")
val damlGenerated = layout.buildDirectory.dir("generated/sources/daml")
val damlCodegen by tasks.registering(Exec::class) {
    description = "Generates Java classes from the loan-model DAR"
    inputs.file(damlDar)
    outputs.dir(damlGenerated)
    doFirst { damlGenerated.get().asFile.deleteRecursively() }
    commandLine(
        "dpm", "codegen-java",
        "${damlDar.asFile.absolutePath}=com.hamzaaziz.loansync.daml",
        "-o", damlGenerated.get().asFile.absolutePath,
    )
}
sourceSets {
    main {
        java.srcDir(damlCodegen)
    }
}

tasks.register<JavaExec>("ledgerSmoke") {
